const DICTS: Record<string, Dict> = { en, ar, de, es, fr };
export const LANGUAGES = [
  { code: 'en', label: 'English' },
  { code: 'ar', label: 'العربية' },
  { code: 'de', label: 'Deutsch' },
  { code: 'es', label: 'Español' },
  { code: 'fr', label: 'Français' },
];

const LANG_KEY = 'c1_lang';

let current: string = 'en';
let listeners: (() => void)[] = [];

export function t(k: keyof Dict): string {
  const dict = DICTS[current] || en;
  return dict[k] || en[k] || String(k);
}
export function currentLang() {
  return current;
}
export function isRTL() {
  return current === 'ar';
}
export function subscribe(fn: () => void) {
  listeners.push(fn);
  return () => {
    listeners = listeners.filter((l) => l !== fn);
  };
}
export async function loadLang() {
  const stored = await AsyncStorage.getItem(LANG_KEY);
  const guess = stored || (Localization.getLocales?.()[0]?.languageCode ?? 'en');
  const code = DICTS[guess] ? guess : 'en';
  current = code;
  const rtl = code === 'ar';
  if (I18nManager.isRTL !== rtl) {
    try {
      I18nManager.allowRTL(rtl);
      I18nManager.forceRTL(rtl);
    } catch {}
  }
  return code;
}
export async function setLang(code: string) {
  if (!DICTS[code]) return;
  current = code;
  await AsyncStorage.setItem(LANG_KEY, code);
  const rtl = code === 'ar';
  try {
    I18nManager.allowRTL(rtl);
    I18nManager.forceRTL(rtl);
  } catch {}
  listeners.forEach((l) => l());
}
